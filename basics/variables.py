"""
变量与数据类型
变量就像一个贴了标签的盒子，用来存放数据。
"""

# ---- 数字 ----
年龄 = 25                # 整数
身高 = 1.75              # 浮点数（小数）
print(f"年龄：{年龄}，身高：{身高}米")

# ---- 字符串 ----
姓名 = "小明"
问候语 = f"你好，我叫{姓名}，今年{年龄}岁"
print(问候语)

# 字符串可以拼接
名 = "张"
姓 = "三"
全名 = 姓 + 名
print("全名：", 全名)

# ---- 布尔值 ----
是学生 = True
在上班 = False
print(f"是学生吗？{是学生}")
print(f"在上班吗？{在上班}")

# ---- 类型查看 ----
print(f"年龄的类型：{type(年龄)}")
print(f"身高的类型：{type(身高)}")
print(f"姓名的类型：{type(姓名)}")
print(f"是学生的类型：{type(是学生)}")

