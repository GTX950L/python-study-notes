# 写一个函数，判断一个数是否为质数
def 是质数吗(数):
    """判断一个数是否为质数"""
    if 数 < 2:
        return False
    for i in range(2, int(数 ** 0.5) + 1):
        if 数 % i == 0:
            return False
    return True

print(f"7 是质数吗？{是质数吗(7)}")
print(f"10 是质数吗？{是质数吗(10)}")
