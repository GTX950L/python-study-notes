# ---- 基本函数定义 ----
def 打招呼(名字):
    """向指定的人打招呼"""
    print(f"你好，{名字}！欢迎来学 Python。")

打招呼("小明")
打招呼("小红")

# ---- 带返回值的函数 ----
def 加法(a, b):
    """返回两个数的和"""
    return a + b

结果 = 加法(3, 5)
print(f"3 + 5 = {结果}")

# ---- 默认参数 ----
def 介绍(姓名, 城市="深圳"):
    """城市有默认值"""
    print(f"{姓名}来自{城市}")

介绍("张三")              # 使用默认城市
介绍("李四", "北京")      # 覆盖默认值

# ---- 多个返回值 ----
def 计算矩形的面积和周长(长, 宽):
    """返回面积和周长"""
    面积 = 长 * 宽
    周长 = 2 * (长 + 宽)
    return 面积, 周长

矩形的面积, 矩形的周长 = 计算矩形的面积和周长(10, 5)
print(f"面积：{矩形的面积}，周长：{矩形的周长}")

# ---- 可变参数（*args） ----
def 求和(*数字):
    """可以接收任意数量的参数"""
    return sum(数字)

print(f"求和结果：{求和(1, 2, 3, 4, 5)}")

# ---- 关键字参数（**kwargs） ----
def 显示信息(**信息):
    """接收键值对形式的参数"""
    for 键, 值 in 信息.items():
        print(f"{键}：{值}")

显示信息(姓名="王五", 年龄=28, 职业="工程师")

