"""
📊 pandas 分组聚合：groupby() + agg()
======================================
按某一列分组，然后对每组进行计算（求和、平均、计数等），
是数据分析中最常用的操作之一。
类似于 Excel 的数据透视表基础操作。
"""

import pandas as pd
import numpy as np

# ============================================================
# 模拟生产数据
# ============================================================

生产数据 = pd.DataFrame({
    "产线":    ["8222", "8222", "8222", "8222", "9610", "9610", "9610",
                "8222", "8222", "9610", "8222", "9610"],
    "设备类型": ["电阻焊", "电阻焊", "注水", "扩孔", "注水", "测温", "测温",
                "电阻焊", "扩孔", "注水", "注水", "测温"],
    "日期":    ["06-01", "06-01", "06-01", "06-01", "06-01", "06-01", "06-02",
                "06-02", "06-02", "06-02", "06-02", "06-02"],
    "产量":    [3200, 2850, 4100, 3600, 5200, 4800, 4900,
                3100, 3550, 5150, 4200, 4750],
    "合格数":  [3180, 2820, 4050, 3580, 5180, 4780, 4880,
                3070, 3520, 5120, 4160, 4720],
    "保养耗时(分)": [30, 35, 45, 25, 40, 28, 32,
                     33, 27, 42, 46, 30],
})

print("📋 原始数据：")
print(生产数据.head(8))
print(f"... 共 {len(生产数据)} 行\n")

# ============================================================
# 一、简单分组统计（单列）
# ============================================================

# 按产线分组，统计产量
print("📊 按产线分组 — 产量汇总：")
按产线 = 生产数据.groupby("产线")["产量"].sum()
print(按产线)
print()

# 按设备类型分组
print("📊 按设备类型分组 — 平均产量：")
按设备 = 生产数据.groupby("设备类型")["产量"].mean()
print(按设备)
print()

# ============================================================
# 二、多列聚合（agg）
# ============================================================

print("📊 多指标聚合：")
统计结果 = 生产数据.groupby("产线").agg({
    "产量":   ["sum", "mean", "count"],     # 总和、均值、计数
    "合格数": "sum",                        # 合格总和
    "保养耗时(分)": ["mean", "max"],        # 平均、最大保养耗时
})
print(统计结果)
print()

# ============================================================
# 三、自定义列名（推荐写法）
# ============================================================

print("📊 自定义聚合列名：")
统计_命名 = (生产数据
    .groupby("产线")
    .agg(
        总产量="产量",          # 简单写法
        平均产量=("产量", "mean"),
        设备数=("产量", "count"),
        总合格=("合格数", "sum"),
        平均保养耗时=("保养耗时(分)", "mean"),
    )
    .reset_index()              # 把产线从索引变回普通列
)
print(统计_命名)
print()

# ============================================================
# 四、计算合格率
# ============================================================

统计_命名["合格率"] = (统计_命名["总合格"] / 统计_命名["总产量"] * 100).round(2)
统计_命名["合格率"] = 统计_命名["合格率"].astype(str) + "%"
print("📊 加入合格率：")
print(统计_命名)
print()

# ============================================================
# 五、多层级分组
# ============================================================

print("📊 多层级分组（产线 + 设备类型）：")
多层级 = (生产数据
    .groupby(["产线", "设备类型"])
    .agg(
        总产量=("产量", "sum"),
        平均产量=("产量", "mean"),
    )
)
print(多层级)
print()

# ============================================================
# 六、transform — 组内相对计算
# ============================================================

生产数据["高于组平均"] = (
    生产数据.groupby("产线")["产量"].transform("mean") < 生产数据["产量"]
)
print("📊 标记是否高于组平均产量：")
print(生产数据[["产线", "设备类型", "产量", "高于组平均"]])
print()

print("\n" + "=" * 50)
print("💡 关键要点：")
print("  - groupby('列') 是分组的核心")
print("  - agg() 支持多指标聚合，推荐命名元组写法 (列名, 函数)")
print("  - reset_index() 让分组键变回普通列")
print("  - transform() 在组内做计算但保持原形状")
print("  - 多级分组用列表: groupby(['列A', '列B'])")
