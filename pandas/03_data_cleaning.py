"""
🧹 pandas 数据清洗
===================
生产数据不可能是完美的——缺失值、重复行、格式问题、
异常值。数据清洗是分析前最重要的一步。
"""

import pandas as pd
import numpy as np

# ============================================================
# 模拟真实场景：一份"不干净"的保养记录
# ============================================================

数据 = pd.DataFrame({
    "设备编号":   ["D001", "D002", "D003", "D004", "D005", "D005", "D006"],
    "设备名称":   ["电阻焊机01", "注水机01", "扩孔机01", "测温仪01", "电阻焊机02", "电阻焊机02", None],
    "产线":       ["8222", "9610", "8222", None, "8222", "8222", "9610"],
    "日产量":     [3200, 4100, 3600, 5200, np.nan, 2900, 4400],
    "保养日期":   ["2026-06-01", "2026/06/02", "2026-06-03", "2026-06-04", None, "2026-06-02", "2026-06-03"],
    "保养耗时(分)":[30, 45, 999, 25, 35, 35, 28],  # 999 是异常值
})

print("📋 原始数据（含问题）：")
print(数据)
print()

# ============================================================
# 一、查看缺失值
# ============================================================

print("🔍 缺失值分布：")
print(数据.isnull().sum())
print(f"\n   缺失值总数: {数据.isnull().sum().sum()}")
print()

# ============================================================
# 二、处理缺失值
# ============================================================

# 2.1 删除有缺失值的行
数据_删空行 = 数据.dropna()
print("🗑️ 删除含缺失值的行后：")
print(数据_删空行)
print()

# 2.2 填充缺失值
数据_填充 = 数据.copy()
数据_填充["设备名称"] = 数据_填充["设备名称"].fillna("未知设备")       # 字符串填充
数据_填充["产线"]     = 数据_填充["产线"].fillna("待确认")           # 字符串填充
数据_填充["日产量"]   = 数据_填充["日产量"].fillna(数据["日产量"].mean())  # 数值填均值
数据_填充["保养日期"] = 数据_填充["保养日期"].fillna("待补充")
print("📝 填充缺失值后：")
print(数据_填充)
print()

# ============================================================
# 三、处理重复行
# ============================================================

print(f"🔍 重复行数: {数据.duplicated().sum()}")
数据_去重 = 数据.drop_duplicates()
print("🗑️ 删除重复行后：")
print(数据_去重)
print()

# ============================================================
# 四、数据类型转换
# ============================================================

数据_转换 = 数据.copy()
# 统一日期格式
数据_转换["保养日期"] = pd.to_datetime(数据_转换["保养日期"], errors="coerce")
# 日产量转整数
数据_转换["日产量"] = 数据_转换["日产量"].astype("Int64")  # 可空整数

print("📅 日期列转换后数据类型：")
print(数据_转换.dtypes)
print()

# ============================================================
# 五、异常值处理
# ============================================================

# 5.1 识别异常值（保养耗时超过 120 分钟视为异常）
异常掩码 = 数据["保养耗时(分)"] > 120
print(f"🔍 异常值（保养耗时 > 120 分钟）: {异常掩码.sum()} 行")
print(数据[异常掩码])

# 5.2 替换异常值
数据_清洗 = 数据.copy()
数据_清洗.loc[异常掩码, "保养耗时(分)"] = 数据["保养耗时(分)"].median()
print(f"\n📝 用中位数替换异常值后：")
print(数据_清洗[["设备编号", "保养耗时(分)"]])
print()

# ============================================================
# 六、链式清洗（一行代码搞定）
# ============================================================

数据_最终 = (数据
    .drop_duplicates()                          # 去重
    .assign(
        设备名称=数据["设备名称"].fillna("未知"),
        产线=数据["产线"].fillna("待确认"),
        # 日产量填均值
    )
)

print("📋 管道清洗结果：")
print(数据_最终)

print("\n" + "=" * 50)
print("💡 关键要点：")
print("  - isnull().sum() 查看每列缺失值数量")
print("  - dropna() 删空行 / fillna() 填空值")
print("  - duplicated() 查重 / drop_duplicates() 去重")
print("  - pd.to_datetime(errors='coerce') 安全日期转换")
print("  - 布尔索引 + loc 定位异常值")
print("  - 管道操作 (.assign .drop .query) 让清洗更简洁")
