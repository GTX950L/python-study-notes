"""
📈 pandas 数据透视表：pivot_table()
===============================
数据透视表是 Excel 里最好用的功能之一，
pandas 的 pivot_table() 能做到同样的事，而且更灵活。
"""

import pandas as pd
import numpy as np

# ============================================================
# 模拟生产数据
# ============================================================

数据 = pd.DataFrame({
    "日期":     ["06-01"] * 4 + ["06-02"] * 4 + ["06-03"] * 4,
    "产线":     ["8222", "8222", "9610", "9610"] * 3,
    "设备类型": ["电阻焊", "注水", "电阻焊", "注水"] * 3,
    "班次":     ["白班", "夜班", "白班", "夜班"] * 3,
    "产量":     [3200, 4100, 2850, 5200, 3350, 3950, 2900, 5100,
                 3280, 4080, 2820, 5150],
    "合格数":   [3180, 4080, 2820, 5180, 3320, 3920, 2880, 5070,
                 3250, 4050, 2790, 5120],
    "不合格数": [],  # 计算出来
})

数据["不合格数"] = 数据["产量"] - 数据["合格数"]
数据["合格率"] = (数据["合格数"] / 数据["产量"] * 100).round(2)

print("📋 原始数据：")
print(数据)
print()

# ============================================================
# 一、最基础透视表
# ============================================================

print("📊 按产线统计总产量（sum）：")
表格1 = pd.pivot_table(数据, values="产量", index="产线", aggfunc="sum")
print(表格1)
print()

# ============================================================
# 二、多值聚合 + 多维度
# ============================================================

print("📊 按产线 + 设备类型，统计产量和合格率：")
表格2 = pd.pivot_table(
    数据,
    values=["产量", "合格率"],   # 要汇总的列
    index=["产线", "设备类型"], # 行分组
    aggfunc=["sum", "mean"],     # 算总和和均值
)
print(表格2)
print()

# ============================================================
# 三、带列分组的透视表（columns 参数）
# ============================================================

print("📊 按产线分组，按班次做列对比：")
表格3 = pd.pivot_table(
    数据,
    values="产量",
    index="产线",
    columns="班次",
    aggfunc="sum",
    fill_value=0,               # 空值填 0
)
print(表格3)
print()

# ============================================================
# 四、多行 + 多列 透视（最常用）
# ============================================================

print("📊 产线×设备类型 为行，班次为列：")
表格4 = pd.pivot_table(
    数据,
    values="产量",
    index=["产线", "设备类型"],
    columns="班次",
    aggfunc="sum",
    fill_value=0,
    margins=True,               # 显示总计行/列
    margins_name="合计",
)
print(表格4)
print()

# ============================================================
# 五、计算合格率透视表
# ============================================================

print("📊 按产线 + 设备类型，看合格率（mean）：")
表格5 = pd.pivot_table(
    数据,
    values="合格率",
    index=["产线", "设备类型"],
    aggfunc="mean",             # 合格率要取平均
).round(2)
print(表格5)
print()

# ============================================================
# 六、重置索引（恢复成普通 DataFrame）
# ============================================================

表格6 = 表格5.reset_index()
print("📋 重置索引后（方便导出 Excel）：")
print(表格6)
print()

# ============================================================
# 七、交叉表（更简洁的计数透视）
# ============================================================

print("📊 交叉表：产线 × 班次 出现次数：")
交叉表 = pd.crosstab(index=数据["产线"], columns=数据["班次"])
print(交叉表)
print()

print("\n" + "=" * 50)
print("💡 关键要点：")
print("  - pivot_table() 是 groupby + agg 的透视版")
print("  - values   = 要汇总的列")
print("  - index    = 行分组（可以是多列）")
print("  - columns  = 列分组（展示维度）")
print("  - aggfunc  = 聚合方式（sum/mean/count）")
print("  - margins  = 是否显示总计行/列")
print("  - crosstab() 专门做计数交叉表，更简洁")
