"""
📊 pandas 基础：DataFrame 和 Series
====================================
pandas 是 Python 数据分析的核心库，两大基础数据结构：
- Series：一维带标签数组（类似 Excel 的一列）
- DataFrame：二维表格（类似 Excel 的一个工作表）
"""

import pandas as pd

# ============================================================
# 一、Series — 一维数据
# ============================================================

# 从列表创建
产量_series = pd.Series([120, 135, 142, 118, 155], name="日产量")
print("📋 从列表创建 Series：")
print(产量_series)
print()

# 自定义索引
日期 = ["周一", "周二", "周三", "周四", "周五"]
产量_日期 = pd.Series([120, 135, 142, 118, 155], index=日期, name="日产量")
print("📋 带自定义索引的 Series：")
print(产量_日期)
print()

# 从字典创建
设备_产量 = pd.Series({
    "电阻焊机01": 3200,
    "电阻焊机02": 2850,
    "注水机01":   4100,
    "扩孔机01":   3600,
})
print("📋 从字典创建 Series：")
print(设备_产量)
print()

# Series 的常用操作
print(f"🔍 索引访问: 产量_日期['周三'] = {产量_日期['周三']}")
print(f"📊 统计信息: 均值={产量_日期.mean()}, 最大值={产量_日期.max()}, 总和={产量_日期.sum()}")
print(f"🔎 过滤: 产量 > 130 →\n{产量_日期[产量_日期 > 130]}")

print("\n" + "=" * 50)

# ============================================================
# 二、DataFrame — 二维表格
# ============================================================

# 从字典创建（最常用方式）
保养数据 = pd.DataFrame({
    "设备名称":   ["电阻焊机01", "电阻焊机02", "注水机01", "扩孔机01", "测温仪01"],
    "产线":       ["8222", "8222", "9610", "8222", "9610"],
    "日产量":     [3200, 2850, 4100, 3600, 5200],
    "周保养日期": ["2026-06-01", "2026-06-02", "2026-06-01", "2026-06-03", "2026-06-02"],
    "月保养日期": ["2026-05-28", "2026-05-30", "2026-05-27", "2026-06-01", "2026-05-29"],
    "是否合格":   [True, True, False, True, True],
})

print("📋 从字典创建 DataFrame：")
print(保养数据)
print()

# 查看基本信息
print(f"📏 形状: {保养数据.shape}  (行列)")
print(f"📋 列名: {list(保养数据.columns)}")
print(f"📊 数据类型:\n{保养数据.dtypes}")
print()

# 行列访问
print(f"🔍 访问列: 保养数据['设备名称']\n{保养数据['设备名称']}")
print(f"\n🔍 访问多列:\n{保养数据[['设备名称', '日产量']]}")
print(f"\n🔍 按索引访问行: 保养数据.iloc[0]\n{保养数据.iloc[0]}")
print(f"\n🔍 按标签访问行: 保养数据.loc[0, '日产量'] = {保养数据.loc[0, '日产量']}")
print()

# 简单筛选
print("🔎 筛选 8222 线设备：")
print(保养数据[保养数据["产线"] == "8222"])
print(f"\n🔎 产量大于 3500 的设备：")
print(保养数据[保养数据["日产量"] > 3500])

print("\n" + "=" * 50)
print("💡 关键要点：")
print("  - Series = 一列数据 + 索引标签")
print("  - DataFrame = 多列 Series 的集合")
print("  - .loc[] 按标签，.iloc[] 按位置")
print("  - 布尔索引: df[df['列'] > 值]")
